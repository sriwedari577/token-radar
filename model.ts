// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The scoring arithmetic lives in dashboard/logic.js, shared with the page so the board's implied
// values and the page's breakdowns are one computation. This file carries the snapshot's shape,
// the board's assembly, the gate's own checks, and the dashboard's dataset.

// logic.js is a plain script the dashboard loads with a classic <script> tag, so Node reads it
// as a CommonJS module: take its single exported object as the default import.
import radarLogic from '../dashboard/logic.js';
const { impliedValue, isPreToken, isRankable, farmSteps, ageDays, MODEL, MODEL_VERSION } = radarLogic as any;

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export const MODEL_CONSTANTS = MODEL;
export const MODEL_LABEL = MODEL_VERSION;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** One row of board.json: the ranked board's row. */
export interface BoardRow {
  rank: number;
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
  token_status: 'pre-token';
  age_days: number | null;
  implied_value_usd: number;
  model: {
    base_value: number;
    growth_pct: number;
    growth_multiplier: number;
    maturity_multiplier: number;
    reach_multiplier: number;
    category_multiplier: number;
    category_group: string;
    damping: number;
    age_days: number | null;
  };
  farm_steps: string[];
}

/** The dashboard's compact view of one row. */
